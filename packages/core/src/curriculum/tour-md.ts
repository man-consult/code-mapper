import type { Curriculum, CurriculumStop } from "./curriculum.ts";

/**
 * Render a curriculum as a single Markdown "tour" note for the Obsidian vault.
 * `[[wikilinks]]` are real edges into the per-file notes, so the reading order
 * is navigable from inside Obsidian. Pure string building — no I/O here.
 */
export function renderTour(cur: Curriculum): string {
  const lines: string[] = [];

  const story =
    cur.order === "entrypoints"
      ? "starting at the entry points and following imports downward, so you see how the app branches into detail"
      : "each file is introduced after the files it depends on, so you never read a file before its building blocks";
  lines.push(
    "---",
    "title: Guided reading order",
    `order: ${cur.order}`,
    `stops: ${cur.totalStops}`,
    `files: ${cur.totalFiles}`,
    `cycles: ${cur.cycles}`,
    "---",
    "",
    `# Guided reading order — ${cur.order === "entrypoints" ? "entry points first" : "foundations first"}`,
    "",
    `A deterministic tour of this repo — **${cur.totalStops} stops** across ${cur.chapters.length} chapters. ` +
      `Order is derived from the import graph: import cycles are folded together and ${story}.`,
    "",
  );

  if (cur.excluded.total > 0) {
    const parts: string[] = [];
    if (cur.excluded.tests) parts.push(`${cur.excluded.tests} test`);
    if (cur.excluded.generated) parts.push(`${cur.excluded.generated} generated`);
    if (cur.excluded.trivial) parts.push(`${cur.excluded.trivial} inert`);
    lines.push(`> Skipped ${cur.excluded.total} file${cur.excluded.total === 1 ? "" : "s"} (${parts.join(", ")}).`, "");
  }
  if (cur.cycles > 0) {
    lines.push(`> ${cur.cycles} import cycle${cur.cycles === 1 ? "" : "s"} folded — cyclic files are flagged "read together".`, "");
  }

  // Table of contents.
  lines.push("## Chapters", "");
  cur.chapters.forEach((ch, i) => {
    lines.push(`${i + 1}. **${ch.title}** — ${ch.stops.length} stop${ch.stops.length === 1 ? "" : "s"}`);
  });
  lines.push("");

  for (const ch of cur.chapters) {
    lines.push("---", "", `## ${ch.title}`, "", `_${ch.blurb}_`, "");
    for (const stop of ch.stops) {
      lines.push(...renderStop(stop));
    }
  }

  lines.push(
    "---",
    "",
    "_Generated by codeflowmap — order is from static analysis, not an LLM. " +
      "Summaries (if present) come from the annotation pass._",
    "",
  );
  return lines.join("\n");
}

function renderStop(stop: CurriculumStop): string[] {
  const out: string[] = [];
  out.push(`### ${stop.order}. [[${stop.id}]]`, "");
  out.push(`\`${roleLabel(stop)}\` · ${stop.why}`, "");
  if (stop.summary) out.push(stop.summary, "");
  if (stop.cluster.length) {
    out.push(`**Read together:** ${stop.cluster.map((c) => `[[${c}]]`).join(", ")}`, "");
  }
  if (stop.seenDeps.length) {
    out.push(`**Builds on (already seen):** ${stop.seenDeps.map((d) => `[[${d}]]`).join(", ")}`, "");
  }
  if (stop.newDeps.length) {
    out.push(`**Pulls in (coming up):** ${stop.newDeps.map((d) => `[[${d}]]`).join(", ")}`, "");
  }
  if (stop.symbols.length) {
    out.push(`**Symbols:** ${stop.symbols.map((s) => `\`${s}\``).join(", ")}`, "");
  }
  return out;
}

function roleLabel(stop: CurriculumStop): string {
  switch (stop.role) {
    case "entrypoint":
      return "entry point";
    default:
      return stop.role;
  }
}
